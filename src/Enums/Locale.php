    /**
     * Returns the canonical BCP 47 form of a language tag. Matching is case-insensitive and accepts
     * Laravel's underscore style, so "de_de" and "DE-de" both become "de-DE".
     */
    public static function canonicalize(string $tag): string
    {
        $subtags = explode('-', str_replace('_', '-', $tag));

        foreach ($subtags as $index => $subtag) {
            $subtags[$index] = match (true) {
                $index === 0 => strtolower($subtag),
                strlen($subtag) === 4 => ucfirst(strtolower($subtag)),
                default => strtoupper($subtag),
            };
        }

        $canonical = implode('-', $subtags);

        if (preg_match('/^[a-z]{2,3}(?:-[A-Z][a-z]{3})?(?:-(?:[A-Z]{2}|[0-9]{3}))?$/D', $canonical) !== 1) {
            throw new InvalidArgumentException("Invalid locale [{$tag}].");
        }

        return $canonical;
    }

    /**
     * The tag followed by each shorter prefix, as in RFC 4647 lookup: "zh-Hans-CN", "zh-Hans", "zh".
     *
     * @return list<string>
     */
    public static function lookupChain(string $locale): array
    {
        $subtags = explode('-', $locale);
        $chain = [];

        for ($length = count($subtags); $length > 0; $length--) {
            $chain[] = implode('-', array_slice($subtags, 0, $length));
        }

        return $chain;
    }
